export type StateCode = keyof typeof US_STATES;

/** Case-sensitive: callers upper-case the input first. */
export function isStateCode(value: string): value is StateCode {
  return Object.hasOwn(US_STATES, value);
}

export function stateName(code: StateCode): string {
  return US_STATES[code];
}
